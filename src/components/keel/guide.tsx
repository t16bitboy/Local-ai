export function Guide() {
  const reset = useKeel((s) => s.reset);
  const [armed, setArmed] = useState(false);

  return (
    <div className="flex max-w-2xl flex-col gap-6">
      <header>
        <h2 className="text-3xl">Guide</h2>
        <p className="mt-1 text-muted">What is real in this desk, and what the plan still owes.</p>
      </header>
      {sections.map((section) => (
        <section key={section.title} className="flex flex-col gap-2">
          <h3 className="text-xl">{section.title}</h3>
          <p className="text-base text-muted">{section.body}</p>
        </section>
      ))}
      <section className="rounded-lg bg-surface p-4 shadow-line">
        <h3 className="text-xl">Reset the sample desk</h3>
        <p className="mt-1 text-muted">Puts the launch-week tasks back, clears the brief, and shows the setup again. The plan returns to Free.</p>
        {armed ? (
          <div className="mt-3 flex flex-wrap gap-2">
            <Button
              variant="ink"
              onClick={() => {
                reset();
                setArmed(false);
              }}
            >
              Restore the sample
            </Button>
            <Button variant="ghost" onClick={() => setArmed(false)}>
              Cancel
            </Button>
          </div>
        ) : (
          <Button className="mt-3" variant="line" onClick={() => setArmed(true)}>
            Reset
          </Button>
        )}
      </section>
    </div>
  );
}
